import { randomBytes } from "node:crypto";
import { prisma } from "@/server/db/prisma";

/**
 * Idempotent, secure provisioning of the two named NEOLIFE CRM users
 * (Task #037).
 *
 * INVARIANTS (Task #037 requirements 2, 3, 5, 6):
 * - NEVER deletes or overwrites an existing account. Matching is by the
 *   unique email; an existing account keeps its email, name, password hash
 *   and role exactly as-is (identity continuity of the existing Owner).
 *   Only EMPTY optional profile fields (phone / notificationEmail) of an
 *   existing account are backfilled — never existing values.
 * - Created accounts get a cryptographically strong, unique temporary
 *   password (generated by the CALLER-injected generator; production uses
 *   `generateTemporaryPassword()` from this module) and
 *   `mustChangePassword: true` (D-033 flow: forced change on first login).
 * - Authorization roles are exact: owner → "admin", partner → "staff".
 *   The Partner UI label is display-only (`displayRoleLabel`) and NEVER
 *   changes the stored role.
 * - Passwords are hashed by Better Auth. This module never logs, never
 *   returns and never persists a temporary password anywhere except the
 *   caller-provided credential channel (the CLI writes a 0600 file).
 */

export type ProvisionKind = "owner" | "partner";

export type ProvisioningIntent = {
  kind: ProvisionKind;
  name: string;
  email: string;
  phone?: string | null;
  /** Explicit notification preference; null/undefined = fall back to email. */
  notificationEmail?: string | null;
};

export type ProvisionOutcome =
  | {
      status: "created";
      userId: string;
      email: string;
      role: string;
      mustChangePassword: true;
    }
  | {
      status: "existing_preserved";
      userId: string;
      email: string;
      role: string;
      /** Profile fields that were EMPTY and were backfilled now. */
      backfilled: string[];
      /** True when the existing role differs from the intended one — kept,
       * never overwritten; reported for the operator to review. */
      roleMismatch: boolean;
    };

/** Structural email check (locals are lower-cased by the caller). */
export function isValidProvisioningEmail(email: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email) && email.length <= 160;
}

const PHONE_MAX = 24;

export function validateProvisioningIntent(intent: ProvisioningIntent): string | null {
  if (intent.name.trim().length < 1 || intent.name.trim().length > 80) {
    return "Name must be 1–80 characters.";
  }
  if (!isValidProvisioningEmail(intent.email)) {
    return `Invalid email: ${intent.email}`;
  }
  if (intent.phone !== null && intent.phone !== undefined && intent.phone !== "") {
    if (intent.phone.length > PHONE_MAX) {
      return `Phone number is too long for ${intent.email}.`;
    }
  }
  if (
    intent.notificationEmail !== null &&
    intent.notificationEmail !== undefined &&
    intent.notificationEmail !== "" &&
    !isValidProvisioningEmail(intent.notificationEmail)
  ) {
    return `Invalid notification email for ${intent.email}.`;
  }
  return null;
}

/**
 * Cryptographically strong URL-safe temporary password.
 * 144 bits of entropy from CSPRNG randomBytes; unique per call. Never
 * hardcoded, never logged, never committed — callers persist the value ONLY
 * through their secure delivery channel (0600 credentials file).
 */
export function generateTemporaryPassword(): string {
  return randomBytes(18).toString("base64url");
}

/**
 * Provision one intended human user, idempotently.
 *
 * @param getTemporaryPassword — injectable for deterministic tests; the CLI
 *   passes `generateTemporaryPassword`.
 */
export async function provisionCrmUser(
  intent: ProvisioningIntent,
  getTemporaryPassword: () => Promise<string> | string = generateTemporaryPassword,
): Promise<ProvisionOutcome> {
  const validationError = validateProvisioningIntent(intent);
  if (validationError) {
    throw new Error(validationError);
  }
  const email = intent.email.trim().toLowerCase();
  const name = intent.name.trim();
  const desiredRole = intent.kind === "owner" ? "admin" : "staff";
  const phone = intent.phone && intent.phone.trim() !== "" ? intent.phone.trim() : null;
  const notificationEmail =
    intent.notificationEmail && intent.notificationEmail.trim() !== ""
      ? intent.notificationEmail.trim().toLowerCase()
      : null;

  const existing = await prisma.user.findUnique({
    where: { email },
    select: {
      id: true,
      role: true,
      phone: true,
      notificationEmail: true,
      isActive: true,
    },
  });

  if (existing) {
    // EXISTING ACCOUNT — preserve identity, access and credentials.
    // Only backfill EMPTY optional profile fields; existing values (including
    // role and activation state) are never modified.
    const backfilled: string[] = [];
    const data: { phone?: string; notificationEmail?: string } = {};
    if (phone && !existing.phone) {
      data.phone = phone;
      backfilled.push("phone");
    }
    if (notificationEmail && !existing.notificationEmail) {
      data.notificationEmail = notificationEmail;
      backfilled.push("notificationEmail");
    }
    if (Object.keys(data).length > 0) {
      await prisma.user.update({ where: { id: existing.id }, data });
    }
    return {
      status: "existing_preserved",
      userId: existing.id,
      email,
      role: existing.role,
      backfilled,
      // A different existing role is REPORTED, never rewritten (ownership
      // and identity continuity outrank the intended role check).
      roleMismatch: existing.role !== desiredRole,
    };
  }

  // NEW ACCOUNT — actual creation goes through Better Auth so the password
  // is hashed by the auth library (never stored in plaintext by this app).
  const { auth } = await import("@/lib/auth");
  const temporaryPassword = await getTemporaryPassword();
  if (temporaryPassword.length < 8) {
    throw new Error("Generated temporary password is too short.");
  }
  const signUp = await auth.api.signUpEmail({
    body: { name, email, password: temporaryPassword },
  });
  const userId = signUp?.user?.id;
  if (!userId) {
    throw new Error(`Better Auth returned no user id when creating ${email}.`);
  }

  // role and mustChangePassword are server-controlled (Better Auth
  // `additionalFields` with input: false for role/isActive) — set via Prisma
  // exactly as the D-033 provisioning flow does.
  await prisma.user.update({
    where: { id: userId },
    data: {
      role: desiredRole,
      mustChangePassword: true,
      ...(phone ? { phone } : {}),
      ...(notificationEmail ? { notificationEmail } : {}),
    },
  });

  return {
    status: "created",
    userId,
    email,
    role: desiredRole,
    mustChangePassword: true,
  };
}

export interface ProvisioningReportEntry {
  intent: ProvisioningIntent;
  outcome: ProvisionOutcome;
}

/**
 * Provision all provided intents in order, idempotently, and NEVER delete
 * anything. Any failure aborts with the already-processed entries reported.
 */
export async function provisionCrmUsers(
  intents: ProvisioningIntent[],
  getTemporaryPassword?: () => Promise<string> | string,
): Promise<ProvisioningReportEntry[]> {
  const entries: ProvisioningReportEntry[] = [];
  for (const intent of intents) {
    const outcome = await provisionCrmUser(intent, getTemporaryPassword);
    entries.push({ intent, outcome });
  }
  return entries;
}
